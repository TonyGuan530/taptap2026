import fs from 'node:fs';
import path from 'node:path';
import {browser,check} from './v8-browser-harness.mjs';
const root=process.cwd(),dir=path.join(root,'.codex-tmp/inkbound-v10');fs.mkdirSync(dir,{recursive:true});
const base=process.env.INKBOUND_V10_SITE||'http://127.0.0.1:8788/';
const b=await browser(),errors=[],evidence=[];
try{
  const page=await b.newPage({viewport:{width:1280,height:900}});
  page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  page.on('response',r=>{if(r.status()>=400)errors.push('HTTP '+r.status()+' '+r.url());});
  await page.goto(new URL('inkbound-v10.html',base).href,{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>[...document.images].every(i=>i.complete&&i.naturalWidth>0),null,{timeout:45000});
  check(await page.locator('h1').innerText().then(t=>t.includes('笔迹')),'V10 landing headline visible');
  await page.screenshot({path:path.join(dir,'entry-desktop.png')});
  const video=page.locator('#gameplay');await video.scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>document.getElementById('gameplay').readyState>=1,null,{timeout:45000});
  const media=await video.evaluate(v=>({duration:v.duration,width:v.videoWidth,height:v.videoHeight,url:v.currentSrc}));
  check(media.duration>10&&media.width===960&&media.height===540,'actual gameplay MP4 metadata and resolution');
  await video.evaluate(async v=>{v.muted=true;await v.play();});await page.waitForTimeout(1300);
  check(await video.evaluate(v=>v.currentTime>.5),'actual gameplay video plays');await video.evaluate(v=>v.pause());evidence.push({phase:'video',...media});
  const iframe=page.locator('#game');await iframe.scrollIntoViewIfNeeded();
  const frameURL=await iframe.getAttribute('src');
  check(frameURL==='builds/demo-06-inkbound-v10/index.html','iframe retains GitHub project base path');
  await iframe.evaluate(f=>{const u=new URL(f.src);u.searchParams.set('qa','1');f.src=u.href;});
  await page.waitForTimeout(1500);
  const frame=page.frames().find(f=>f.url().includes('/builds/demo-06-inkbound-v10/'));
  check(Boolean(frame),'iframe points to new V10 build');
  await frame.waitForFunction(()=>window.__v10_ink_qa,null,{timeout:60000});
  const game=await frame.evaluate(()=>window.__v10_ink_qa);
  check(game.version===10&&game.ui.intro,'embedded V10 actually boots its character introduction');
  evidence.push({phase:'embedded',url:frame.url(),version:game.version});
  const box=await iframe.boundingBox();
  await page.mouse.click(box.x+game.ui.buttons.begin[0]*box.width/960,box.y+game.ui.buttons.begin[1]*box.height/540);
  await frame.waitForFunction(()=>!window.__v10_ink_qa.ui.intro,null,{timeout:10000});
  const before=await frame.evaluate(()=>window.__v10_ink_qa.player[0]);
  await page.keyboard.down('d');await page.waitForTimeout(500);await page.keyboard.up('d');
  await frame.waitForFunction(x=>window.__v10_ink_qa.player[0]>x+.3,before,{timeout:10000});
  evidence.push({phase:'embedded-input',method:'actual page mouse and keyboard',moved:true});
  await page.screenshot({path:path.join(dir,'entry-game.png')});await page.close();
  const mobile=await b.newPage({viewport:{width:390,height:844}});
  mobile.on('pageerror',e=>errors.push(String(e)));
  await mobile.goto(new URL('inkbound-v10.html',base).href,{waitUntil:'domcontentloaded'});
  await mobile.waitForFunction(()=>[...document.images].every(i=>i.complete&&i.naturalWidth>0),null,{timeout:45000});
  check(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile video page has no horizontal overflow');
  await mobile.screenshot({path:path.join(dir,'entry-mobile.png')});
  evidence.push({phase:'mobile',width:390,overflow:false});await mobile.close();
  check(!errors.length,'entry and embed have no browser/console errors');
}finally{await b.close();fs.writeFileSync(path.join(dir,'entry-qa.json'),JSON.stringify({base,errors,evidence},null,2)+'\n');}
